    public async Task<bool> HardDeleteCampaignAsync(Guid campaignId, CancellationToken cancellationToken = default)
    {
        _logger.LogMethodEntry(nameof(HardDeleteCampaignAsync), new { campaignId });

        using var connection = new SqlConnection(_connectionString);
        await connection.OpenAsync(cancellationToken).ConfigureAwait(false);
        using var transaction = connection.BeginTransaction();

        try
        {
            // First, set campaign status to 'Deleting' for audit trail
            const string updateStatusSql = "UPDATE Campaigns SET Status = 'Deleting', ModifiedAt = @ModifiedAt WHERE Id = @Id";
            await connection.ExecuteAsync(new CommandDefinition(updateStatusSql, new { Id = campaignId, ModifiedAt = DateTime.UtcNow }, transaction, cancellationToken: cancellationToken)).ConfigureAwait(false);

            // Delete all related records in order (to respect foreign keys)

            // 1. Delete remediation actions (table may not exist yet)
            var remediationRows = 0;
            try
            {
                const string deleteRemediationSql = "DELETE FROM RemediationActions WHERE CampaignId = @CampaignId";
                remediationRows = await connection.ExecuteAsync(new CommandDefinition(deleteRemediationSql, new { CampaignId = campaignId }, transaction, cancellationToken: cancellationToken)).ConfigureAwait(false);
                _logger.LogInformation("Deleted {Count} remediation actions for campaign {CampaignId}", remediationRows, campaignId);
            }
            catch (SqlException ex) when (ex.Message.Contains("Invalid object name"))
            {
                _logger.LogDebug("RemediationActions table does not exist, skipping");
            }

            // 2. Delete decision history (via AssignmentId since ReviewDecisionHistory doesn't have CampaignId)
            const string deleteHistorySql = @"
                DELETE FROM ReviewDecisionHistory
                WHERE AssignmentId IN (
                    SELECT Id FROM AccessReviewAssignments WHERE CampaignId = @CampaignId
                )";
            var historyRows = await connection.ExecuteAsync(new CommandDefinition(deleteHistorySql, new { CampaignId = campaignId }, transaction, cancellationToken: cancellationToken)).ConfigureAwait(false);
            _logger.LogInformation("Deleted {Count} decision history records for campaign {CampaignId}", historyRows, campaignId);

            // 3. Delete assignments
            const string deleteAssignmentsSql = "DELETE FROM AccessReviewAssignments WHERE CampaignId = @CampaignId";
            var assignmentRows = await connection.ExecuteAsync(new CommandDefinition(deleteAssignmentsSql, new { CampaignId = campaignId }, transaction, cancellationToken: cancellationToken)).ConfigureAwait(false);
            _logger.LogInformation("Deleted {Count} assignments for campaign {CampaignId}", assignmentRows, campaignId);

            // 4. Finally, delete the campaign itself
            const string deleteCampaignSql = "DELETE FROM Campaigns WHERE Id = @Id";
            var campaignRows = await connection.ExecuteAsync(new CommandDefinition(deleteCampaignSql, new { Id = campaignId }, transaction, cancellationToken: cancellationToken)).ConfigureAwait(false);

            transaction.Commit();

            _logger.LogInformation("Hard deleted campaign {CampaignId} - Removed {AssignmentCount} assignments, {HistoryCount} history records, {RemediationCount} remediation actions",
                campaignId, assignmentRows, historyRows, remediationRows);

            return campaignRows > 0;
        }
        catch (Exception ex)
        {
            transaction.Rollback();
            _logger.LogError(ex, "Error hard deleting campaign {CampaignId}", campaignId);
            throw;
        }
        finally
        {
            _logger.LogMethodExit(nameof(HardDeleteCampaignAsync));
        }
    }

