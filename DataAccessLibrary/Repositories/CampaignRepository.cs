        const string sql = @"
SELECT * FROM Campaigns
WHERE RecurrenceType IS NOT NULL
  AND RecurrenceType <> 'None'
  AND IsRecurrencePaused = 0
  AND IsRecurrenceClone = 0
  AND NextScheduledRun IS NOT NULL
