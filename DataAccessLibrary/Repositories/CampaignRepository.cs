    (SELECT COUNT(*) FROM AccessReviewAssignments a
     INNER JOIN Campaigns c ON a.CampaignId = c.Id
     WHERE a.Status IN ('Approved', 'Denied', 'Completed')
       AND CAST(a.CompletedAt AS DATE) = CAST(GETUTCDATE() AS DATE)) AS CompletedToday,

    (SELECT COUNT(*) FROM Campaigns WHERE Status = 'Active') AS ActiveCampaigns";

        using var connection = new SqlConnection(_connectionString);
        return await connection.QueryFirstAsync<CaseDashboardStats>(
            new CommandDefinition(sql, cancellationToken: cancellationToken)).ConfigureAwait(false);
    }

