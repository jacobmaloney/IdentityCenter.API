     INNER JOIN Campaigns c ON a.CampaignId = c.Id
     WHERE a.Status = 'Pending' AND c.Status = 'Active') AS TotalPending,

    (SELECT COUNT(*) FROM AccessReviewAssignments a
     INNER JOIN Campaigns c ON a.CampaignId = c.Id
     WHERE a.Status = 'Pending' AND c.Status = 'Active'
       AND a.ReviewerId = '00000000-0000-0000-0000-000000000000') AS NoManagerCases,

    (SELECT COUNT(*) FROM AccessReviewAssignments a
     INNER JOIN Campaigns c ON a.CampaignId = c.Id
     WHERE a.Status = 'Pending' AND c.Status = 'Active'
