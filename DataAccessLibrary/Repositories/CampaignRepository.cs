    public async Task<CampaignStatistics> GetCampaignStatisticsAsync(Guid campaignId, CancellationToken cancellationToken = default)
    {
        const string sql = @"
SELECT
    @CampaignId AS CampaignId,
    COUNT(*) AS TotalAssignments,
    SUM(CASE WHEN Status IN ('Approved', 'Denied', 'Completed') THEN 1 ELSE 0 END) AS CompletedAssignments,
    SUM(CASE WHEN Status = 'Pending' THEN 1 ELSE 0 END) AS PendingAssignments,
    SUM(CASE WHEN Status = 'Pending' AND DueDate < GETUTCDATE() THEN 1 ELSE 0 END) AS OverdueAssignments,
    SUM(CASE WHEN Decision = 'Approved' THEN 1 ELSE 0 END) AS ApprovedCount,
    SUM(CASE WHEN Decision = 'Denied' THEN 1 ELSE 0 END) AS DeniedCount,
    CASE
        WHEN COUNT(*) = 0 THEN 0
        ELSE (CAST(SUM(CASE WHEN Status IN ('Approved', 'Denied', 'Completed') THEN 1 ELSE 0 END) AS DECIMAL) / COUNT(*)) * 100
    END AS CompletionPercentage,
    ISNULL(DATEDIFF(day, GETUTCDATE(), (SELECT DueDate FROM Campaigns WHERE Id = @CampaignId)), 0) AS DaysRemaining
FROM AccessReviewAssignments
WHERE CampaignId = @CampaignId";

        using var connection = new SqlConnection(_connectionString);
        var stats = await connection.QueryFirstOrDefaultAsync<CampaignStatistics>(new CommandDefinition(sql, new { CampaignId = campaignId }, cancellationToken: cancellationToken)).ConfigureAwait(false);
        return stats ?? new CampaignStatistics { CampaignId = campaignId };
    }

