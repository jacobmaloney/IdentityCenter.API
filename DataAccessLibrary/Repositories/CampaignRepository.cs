    public async Task<List<AccessReviewAssignment>> GetAssignmentsFilteredAsync(CaseFilterCriteria filter, int limit = 500, CancellationToken cancellationToken = default)
    {
        var sql = @"
SELECT TOP (@Limit) a.*, c.Name as CampaignName
FROM AccessReviewAssignments a
INNER JOIN Campaigns c ON a.CampaignId = c.Id
WHERE c.Status NOT IN ('Deleted', 'Deleting')";

        var parameters = new DynamicParameters();
        parameters.Add("Limit", limit);

        if (filter.CampaignId.HasValue)
        {
            sql += " AND a.CampaignId = @CampaignId";
            parameters.Add("CampaignId", filter.CampaignId.Value);
        }

        if (!string.IsNullOrEmpty(filter.StatusFilter))
        {
            if (filter.StatusFilter == "Overdue")
            {
                sql += " AND a.Status = 'Pending' AND a.DueDate < GETUTCDATE()";
            }
            else
            {
                sql += " AND a.Status = @StatusFilter";
                parameters.Add("StatusFilter", filter.StatusFilter);
            }
        }

        if (filter.NoManagerOnly)
        {
            sql += " AND a.ReviewerId = '00000000-0000-0000-0000-000000000000'";
        }

        if (!string.IsNullOrEmpty(filter.SearchText))
        {
            sql += " AND a.ReviewTargetName LIKE @SearchText";
            parameters.Add("SearchText", "%" + filter.SearchText + "%");
        }

        if (filter.ReviewerId.HasValue)
        {
            sql += " AND a.ReviewerId = @ReviewerId";
            parameters.Add("ReviewerId", filter.ReviewerId.Value);
        }

        sql += " ORDER BY a.AssignedAt DESC";

        using var connection = new SqlConnection(_connectionString);
        var assignments = await connection.QueryAsync<AccessReviewAssignment>(
            new CommandDefinition(sql, parameters, cancellationToken: cancellationToken)).ConfigureAwait(false);
        return assignments.ToList();
    }

